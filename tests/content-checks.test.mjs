// Run: node --test <skill-dir>/tests/
//
// The secret patterns every validator shares: the skill's own token and key
// names are caught in shell, env and JSON forms, and naming them in prose is
// not.

import assert from "node:assert/strict";
import { test } from "node:test";

import { findSecrets } from "../scripts/content-checks.mjs";

const value = "Zq3x9VbN2mK7pL4tR8wY1cF6hJ0sD5gA_-eUoIiTy";

test("the skill's own secrets are caught in every assignment form", () => {
  for (const name of ["CLOUDFLARE_API_TOKEN", "CF_ACCESS_TOKEN", "ACCESS_API_TOKEN", "SHARE_COOKIE_KEY"]) {
    for (const text of [`export ${name}=${value}`, `${name}: "${value}"`, `{"${name}": "${value}"}`, `'${name}' = '${value}'`]) {
      assert.ok(findSecrets(text).length, `${text} was not caught`);
    }
  }
  // A cookie key set by hand may be plain base64.
  assert.ok(findSecrets("SHARE_COOKIE_KEY=+q3x9VbN/2mK7pL4tR8wY1cF6hJ0sD5gA==").length);
});

test("naming a secret in prose is not a secret", () => {
  for (const text of [
    "Set the Pages secret `ACCESS_API_TOKEN` once.",
    "SHARE_COOKIE_KEY is generated by setup.mjs.",
    "CF_ACCESS_TOKEN=... in the shell that runs these scripts",
  ]) {
    assert.deepEqual(findSecrets(text), [], text);
  }
});
